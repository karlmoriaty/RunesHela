using System;
using System.Collections.Generic;
using System.Text;

namespace RunesHela.Generator;

internal static class Emitter
{
    public static string Emit(string appName, IReadOnlyList<CommandNode> roots)
    {
        var allNodes = new List<CommandNode>();
        var indexes = new Dictionary<CommandNode, int>();
        CollectNodes(roots, allNodes, indexes);

        var builder = new StringBuilder(65536);

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Threading;");
        builder.AppendLine("using System.Threading.Tasks;");
        builder.AppendLine();
        builder.AppendLine("namespace RunesHela.Generated;");
        builder.AppendLine();
        builder.AppendLine("internal static class __RunesHelaEntry");
        builder.AppendLine("{");
        builder.Append("    private const string AppName = ").Append(CodeLiteral.String(appName)).AppendLine(";");
        builder.AppendLine();

        AppendConst(builder, "RootHelpText", HelpText.Build(appName, null, roots, isRoot: true));
        AppendConst(builder, "RootHelpJson", HelpJson.Build(appName, null, roots, isRoot: true));
        AppendConst(builder, "DescribeJson", DescribeJson.Build(appName, roots));
        AppendConst(builder, "CompletionBash", CompletionScripts.Bash(appName, roots));
        AppendConst(builder, "CompletionZsh", CompletionScripts.Zsh(appName, roots));
        AppendConst(builder, "CompletionFish", CompletionScripts.Fish(appName, roots));
        AppendConst(builder, "CompletionPowerShell", CompletionScripts.PowerShell(appName, roots));
        AppendConst(builder, "DocsMarkdown", DocsMarkdown.Build(appName, roots));
        AppendConst(builder, "ManRoff", ManRoff.Build(appName, roots));

        for (var i = 0; i < allNodes.Count; i++)
        {
            AppendConst(builder, "HelpText" + i, HelpText.Build(appName, allNodes[i], allNodes[i].Children, isRoot: false));
            AppendConst(builder, "HelpJson" + i, HelpJson.Build(appName, allNodes[i], allNodes[i].Children, isRoot: false));
        }

        builder.AppendLine();
        AppendCandidates(builder, "CommandCandidates", GetCommandNames(roots));
        AppendCandidates(builder, "CompletionRoot", CompletionData.RootCandidates(roots), allowEmpty: true);

        for (var i = 0; i < allNodes.Count; i++)
        {
            AppendCandidates(builder, "Completion" + i, CompletionData.Candidates(allNodes[i], isRoot: false), allowEmpty: true);

            if (allNodes[i].Model.Options.Count > 0)
            {
                AppendCandidates(builder, "OptionCandidates" + i, GetOptionNames(allNodes[i].Model));
            }

            if (allNodes[i].Children.Count > 0)
            {
                AppendCandidates(builder, "SubcommandCandidates" + i, GetCommandNames(allNodes[i].Children));
            }
        }

        AppendRootRun(builder, roots, indexes);

        for (var i = 0; i < allNodes.Count; i++)
        {
            AppendNodeRun(builder, allNodes[i], i, indexes);
            AppendNodeInvoke(builder, allNodes[i], i);
            BindingEmitter.Emit(builder, allNodes[i], i);
        }

        AppendArtifactHelpers(builder, allNodes);
        AppendWriteHelpers(builder, allNodes);
        AppendAwaitHelpers(builder);

        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("internal static class __RunesHelaModuleInitializer");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void Initialize()");
        builder.AppendLine("    {");
        builder.AppendLine("        global::RunesHela.RunesHelaApp.RegisterEntry(global::RunesHela.Generated.__RunesHelaEntry.RunAsync);");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static void CollectNodes(
        IReadOnlyList<CommandNode> nodes,
        List<CommandNode> allNodes,
        Dictionary<CommandNode, int> indexes)
    {
        foreach (var node in nodes)
        {
            indexes[node] = allNodes.Count;
            allNodes.Add(node);
            CollectNodes(node.Children, allNodes, indexes);
        }
    }

    private static void AppendConst(StringBuilder builder, string name, string value)
    {
        builder.Append("    private const string ").Append(name).Append(" = ").Append(CodeLiteral.String(value)).AppendLine(";");
    }

    private static void AppendCandidates(StringBuilder builder, string name, List<string> values, bool allowEmpty = false)
    {
        if (values.Count == 0 && !allowEmpty)
        {
            return;
        }

        if (values.Count == 0)
        {
            builder.Append("    private static readonly string[] ").Append(name).AppendLine(" = Array.Empty<string>();");
            builder.AppendLine();
            return;
        }

        builder.Append("    private static readonly string[] ").Append(name).AppendLine(" =");
        builder.AppendLine("    [");

        foreach (var value in values)
        {
            builder.Append("        ").Append(CodeLiteral.String(value)).AppendLine(",");
        }

        builder.AppendLine("    ];");
        builder.AppendLine();
    }

    private static List<string> GetCommandNames(IReadOnlyList<CommandNode> nodes)
    {
        var names = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var node in nodes)
        {
            if (seen.Add(node.Model.Name))
            {
                names.Add(node.Model.Name);
            }

            foreach (var alias in node.Model.Aliases)
            {
                if (seen.Add(alias))
                {
                    names.Add(alias);
                }
            }
        }

        return names;
    }

    private static List<string> GetOptionNames(CommandModel model)
    {
        var names = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var option in model.Options)
        {
            if (seen.Add(option.LongName))
            {
                names.Add(option.LongName);
            }

            foreach (var alias in option.Aliases)
            {
                if (seen.Add(alias))
                {
                    names.Add(alias);
                }
            }
        }

        return names;
    }

    private static void AppendRootRun(
        StringBuilder builder,
        IReadOnlyList<CommandNode> roots,
        Dictionary<CommandNode, int> indexes)
    {
        builder.AppendLine("    public static ValueTask<int> RunAsync(string[] args, global::System.IServiceProvider? services, CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        return RunRoot(args.AsSpan(), services, cancellationToken);");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static ValueTask<int> RunRoot(ReadOnlySpan<string> args, global::System.IServiceProvider? services, CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        var json = global::RunesHela.RunesHelaOutputOptions.WantsJson(args);");
        builder.AppendLine("        var commandIndex = -1;");
        builder.AppendLine();
        builder.AppendLine("        for (var i = 0; i < args.Length; i++)");
        builder.AppendLine("        {");
        builder.AppendLine("            var arg = args[i];");
        builder.AppendLine();
        builder.AppendLine("            if (arg == \"--\") break;");
        builder.AppendLine("            if (arg == \"-h\" || arg == \"--help\")");
        builder.AppendLine("            {");
        builder.AppendLine("                WriteRootHelp(json);");
        builder.AppendLine("                return new ValueTask<int>(0);");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            if (arg == \"--version\")");
        builder.AppendLine("            {");
        builder.AppendLine("                global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(global::RunesHela.RunesHelaApp.GetVersion());");
        builder.AppendLine("                return new ValueTask<int>(0);");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            if (arg == \"--format\")");
        builder.AppendLine("            {");
        builder.AppendLine("                if (i + 1 >= args.Length)");
        builder.AppendLine("                    return new ValueTask<int>(global::RunesHela.RunesHelaErrors.MissingValue(string.Empty, \"format\", json));");
        builder.AppendLine("                if (!global::RunesHela.RunesHelaOutputOptions.IsSupportedFormat(args[i + 1]))");
        builder.AppendLine("                    return new ValueTask<int>(global::RunesHela.RunesHelaErrors.UnsupportedFormat(string.Empty, args[i + 1], json));");
        builder.AppendLine("                i++;");
        builder.AppendLine("                continue;");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            if (arg.StartsWith(\"--format=\", StringComparison.Ordinal))");
        builder.AppendLine("            {");
        builder.AppendLine("                if (!global::RunesHela.RunesHelaOutputOptions.IsSupportedFormat(arg.AsSpan(9)))");
        builder.AppendLine("                    return new ValueTask<int>(global::RunesHela.RunesHelaErrors.UnsupportedFormat(string.Empty, arg.Substring(9), json));");
        builder.AppendLine("                continue;");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            if (arg.Length > 2 && arg[0] == '-' && arg[1] == '-' && global::RunesHela.RunesHelaOutputOptions.IsGlobalFlag(arg.AsSpan(2))) continue;");
        builder.AppendLine("            if (arg == \"-y\") continue;");
        builder.AppendLine();
        builder.AppendLine("            commandIndex = i;");
        builder.AppendLine("            break;");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (commandIndex < 0)");
        builder.AppendLine("        {");
        builder.AppendLine("            WriteRootHelp(json);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        var command = args[commandIndex];");
        builder.AppendLine();
        builder.AppendLine("        if (command == \"describe\")");
        builder.AppendLine("        {");
        builder.AppendLine("            global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(DescribeJson);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (command == \"completion\")");
        builder.AppendLine("        {");
        builder.AppendLine("            return RunCompletion(args.Slice(commandIndex + 1), json);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (command == \"docs\")");
        builder.AppendLine("        {");
        builder.AppendLine("            global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(DocsMarkdown);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (command == \"man\")");
        builder.AppendLine("        {");
        builder.AppendLine("            global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(ManRoff);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (command == \"__complete\")");
        builder.AppendLine("        {");
        builder.AppendLine("            return new ValueTask<int>(Complete(args.Slice(commandIndex + 1)));");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        switch (command)");
        builder.AppendLine("        {");

        var emitted = new HashSet<string>(StringComparer.Ordinal);

        foreach (var root in roots)
        {
            AppendCase(builder, emitted, root.Model.Name, indexes[root], "args", "json", "commandIndex");
            foreach (var alias in root.Model.Aliases)
            {
                AppendCase(builder, emitted, alias, indexes[root], "args", "json", "commandIndex");
            }
        }

        builder.AppendLine("            default:");
        builder.AppendLine("                return new ValueTask<int>(global::RunesHela.RunesHelaErrors.UnknownCommand(command, AppName, json, CommandCandidates));");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendCase(
        StringBuilder builder,
        HashSet<string> emitted,
        string name,
        int index,
        string argsVariable,
        string jsonVariable,
        string indexVariable)
    {
        if (!emitted.Add(name))
        {
            return;
        }

        builder.Append("            case ").Append(CodeLiteral.String(name)).AppendLine(":");
        builder.Append("                return RunNode").Append(index)
            .Append("Async(").Append(argsVariable).Append(".Slice(").Append(indexVariable)
            .Append(" + 1), ").Append(jsonVariable).AppendLine(", services, cancellationToken);");
    }

    private static void AppendNodeRun(
        StringBuilder builder,
        CommandNode node,
        int index,
        Dictionary<CommandNode, int> indexes)
    {
        var model = node.Model;

        builder.Append("    private static ValueTask<int> RunNode").Append(index)
            .AppendLine("Async(ReadOnlySpan<string> args, bool json, global::System.IServiceProvider? services, CancellationToken cancellationToken)");
        builder.AppendLine("    {");

        if (node.Children.Count > 0)
        {
            builder.AppendLine("        if (args.Length > 0 && (args[0] == \"-h\" || args[0] == \"--help\"))");
        }
        else
        {
            builder.AppendLine("        if (global::RunesHela.RunesHelaOutputOptions.WantsHelp(args))");
        }

        builder.AppendLine("        {");
        builder.Append("            WriteNode").Append(index).AppendLine("Help(json);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();

        if (node.Children.Count > 0)
        {
            builder.AppendLine("        if (args.Length > 0)");
            builder.AppendLine("        {");
            builder.AppendLine("            switch (args[0])");
            builder.AppendLine("            {");

            var emitted = new HashSet<string>(StringComparer.Ordinal);

            foreach (var child in node.Children)
            {
                AppendChildCase(builder, emitted, child.Model.Name, indexes[child]);
                foreach (var alias in child.Model.Aliases)
                {
                    AppendChildCase(builder, emitted, alias, indexes[child]);
                }
            }

            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        if (args.Length == 0)");
            builder.AppendLine("        {");

            if (model.HandlerName is not null)
            {
                builder.Append("            return InvokeNode").Append(index).AppendLine("Async(args, json, services, cancellationToken);");
            }
            else
            {
                builder.Append("            WriteNode").Append(index).AppendLine("Help(json);");
                builder.AppendLine("            return new ValueTask<int>(0);");
            }

            builder.AppendLine("        }");
            builder.AppendLine();

            if (model.HandlerName is not null)
            {
                builder.Append("        return InvokeNode").Append(index).AppendLine("Async(args, json, services, cancellationToken);");
            }
            else
            {
                builder.Append("        return new ValueTask<int>(global::RunesHela.RunesHelaErrors.UnknownSubcommand(")
                    .Append(CodeLiteral.String(node.Path)).Append(", args[0], json, SubcommandCandidates")
                    .Append(index).AppendLine("));");
            }
        }
        else if (model.HandlerName is not null)
        {
            builder.Append("        return InvokeNode").Append(index).AppendLine("Async(args, json, services, cancellationToken);");
        }
        else
        {
            builder.Append("        return new ValueTask<int>(global::RunesHela.RunesHelaErrors.NotImplemented(")
                .Append(CodeLiteral.String(node.Path)).AppendLine(", json));");
        }

        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendChildCase(StringBuilder builder, HashSet<string> emitted, string name, int index)
    {
        if (!emitted.Add(name))
        {
            return;
        }

        builder.Append("                case ").Append(CodeLiteral.String(name)).AppendLine(":");
        builder.Append("                    return RunNode").Append(index)
            .AppendLine("Async(args.Slice(1), json, services, cancellationToken);");
    }

    private static void AppendNodeInvoke(StringBuilder builder, CommandNode node, int index)
    {
        var model = node.Model;

        if (model.HandlerName is null)
        {
            return;
        }

        builder.Append("    private static ValueTask<int> InvokeNode").Append(index)
            .AppendLine("Async(ReadOnlySpan<string> args, bool json, global::System.IServiceProvider? services, CancellationToken cancellationToken)");
        builder.AppendLine("    {");

        if (model.IsStatic)
        {
            builder.Append("        var bindResult = BindNode").Append(index).AppendLine("(args, services, cancellationToken, json);");
        }
        else
        {
            builder.Append("        var bindResult = BindNode").Append(index)
                .AppendLine("(args, services, cancellationToken, json, out var command);");
        }

        builder.AppendLine("        if (bindResult != 0)");
        builder.AppendLine("        {");
        builder.AppendLine("            return new ValueTask<int>(bindResult);");
        builder.AppendLine("        }");
        builder.AppendLine();

        if (model.Filters.Count == 0)
        {
            AppendHandlerCall(builder, model, model.IsStatic ? model.TypeFullName : "command", "        ");
        }
        else
        {
            builder.AppendLine("        var context = new global::RunesHela.CommandContext");
            builder.AppendLine("        {");
            builder.AppendLine("            CommandPath = " + CodeLiteral.String(node.Path) + ",");
            builder.AppendLine("            Services = services,");
            builder.AppendLine("            CancellationToken = cancellationToken,");
            builder.AppendLine("        };");
            builder.AppendLine();

            for (var i = 0; i < model.Filters.Count; i++)
            {
                builder.Append("        var filter").Append(i).Append(" = new ").Append(model.Filters[i]).AppendLine("();");
            }

            builder.AppendLine();

            var expression = "RunHandler" + index + "Async(" + (model.IsStatic ? string.Empty : "command") + ")";

            for (var i = model.Filters.Count - 1; i >= 0; i--)
            {
                var input = i == 0 ? "context" : "ctx" + i;
                expression = "filter" + i + ".InvokeAsync(" + input + ", ctx" + (i + 1) + " => " + expression + ")";
            }

            builder.Append("        return ").Append(expression).AppendLine(";");

            builder.AppendLine("    }");
            builder.AppendLine();

            builder.Append("    private static ValueTask<int> RunHandler").Append(index).Append("Async(");
            builder.Append(model.IsStatic ? string.Empty : model.TypeFullName + " command").AppendLine(")");
            builder.AppendLine("    {");
            AppendHandlerCall(builder, model, model.IsStatic ? model.TypeFullName : "command", "        ");
            builder.AppendLine("    }");
            builder.AppendLine();
            return;
        }

        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendHandlerCall(
        StringBuilder builder,
        CommandModel model,
        string receiver,
        string indent)
    {
        var call = receiver + "." + model.HandlerName + "()";

        switch (model.ReturnKind)
        {
            case HandlerReturnKind.Void:
                builder.Append(indent).Append(call).AppendLine(";");
                builder.Append(indent).AppendLine("return new ValueTask<int>(0);");
                break;

            case HandlerReturnKind.Int:
                builder.Append(indent).Append("return new ValueTask<int>(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.Task:
                builder.Append(indent).Append("return AwaitTaskAsync(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.TaskOfInt:
                builder.Append(indent).Append("return new ValueTask<int>(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.ValueTask:
                builder.Append(indent).Append("return AwaitValueTaskAsync(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.ValueTaskOfInt:
                builder.Append(indent).Append("return ").Append(call).AppendLine(";");
                break;

            default:
                builder.Append(indent).AppendLine("return new ValueTask<int>(global::RunesHela.RunesHelaExitCode.Failure);");
                break;
        }
    }

    private static void AppendArtifactHelpers(StringBuilder builder, IReadOnlyList<CommandNode> nodes)
    {
        builder.AppendLine("    private static ValueTask<int> RunCompletion(ReadOnlySpan<string> args, bool json)");
        builder.AppendLine("    {");
        builder.AppendLine("        var shell = args.Length > 0 ? args[0] : string.Empty;");
        builder.AppendLine("        var output = global::RunesHela.RunesHelaConsole.Current.Out;");
        builder.AppendLine();
        builder.AppendLine("        if (shell.Equals(\"bash\", StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("        {");
        builder.AppendLine("            output.WriteLine(CompletionBash);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (shell.Equals(\"zsh\", StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("        {");
        builder.AppendLine("            output.WriteLine(CompletionZsh);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (shell.Equals(\"fish\", StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("        {");
        builder.AppendLine("            output.WriteLine(CompletionFish);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (shell.Equals(\"pwsh\", StringComparison.OrdinalIgnoreCase) || shell.Equals(\"powershell\", StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("        {");
        builder.AppendLine("            output.WriteLine(CompletionPowerShell);");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return new ValueTask<int>(global::RunesHela.RunesHelaErrors.UnknownShell(shell, json));");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static int Complete(ReadOnlySpan<string> args)");
        builder.AppendLine("    {");
        builder.AppendLine("        var prefix = args.Length > 0 ? args[args.Length - 1] : string.Empty;");
        builder.AppendLine("        var path = args.Length > 1 ? string.Join(\" \", args.Slice(0, args.Length - 1).ToArray()) : string.Empty;");
        builder.AppendLine("        string[] candidates;");
        builder.AppendLine();
        builder.AppendLine("        switch (path)");
        builder.AppendLine("        {");
        builder.AppendLine("            default:");
        builder.AppendLine("                candidates = Array.Empty<string>();");
        builder.AppendLine("                break;");
        builder.AppendLine("            case \"\":");
        builder.AppendLine("                candidates = CompletionRoot;");
        builder.AppendLine("                break;");

        for (var i = 0; i < nodes.Count; i++)
        {
            builder.Append("            case ").Append(CodeLiteral.String(nodes[i].Path)).AppendLine(":");
            builder.Append("                candidates = Completion").Append(i).AppendLine(";");
            builder.AppendLine("                break;");
        }

        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        var output = global::RunesHela.RunesHelaConsole.Current.Out;");
        builder.AppendLine();
        builder.AppendLine("        foreach (var candidate in candidates)");
        builder.AppendLine("        {");
        builder.AppendLine("            if (candidate.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("            {");
        builder.AppendLine("                output.WriteLine(candidate);");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return 0;");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendWriteHelpers(StringBuilder builder, IReadOnlyList<CommandNode> nodes)
    {
        builder.AppendLine("    private static void WriteRootHelp(bool json)");
        builder.AppendLine("    {");
        builder.AppendLine("        global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(json ? RootHelpJson : RootHelpText);");
        builder.AppendLine("    }");
        builder.AppendLine();

        for (var i = 0; i < nodes.Count; i++)
        {
            builder.Append("    private static void WriteNode").Append(i).AppendLine("Help(bool json)");
            builder.AppendLine("    {");
            builder.Append("        global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(json ? HelpJson").Append(i)
                .Append(" : HelpText").Append(i).AppendLine(");");
            builder.AppendLine("    }");
            builder.AppendLine();
        }
    }

    private static void AppendAwaitHelpers(StringBuilder builder)
    {
        builder.AppendLine("    private static async ValueTask<int> AwaitTaskAsync(Task task)");
        builder.AppendLine("    {");
        builder.AppendLine("        await task.ConfigureAwait(false);");
        builder.AppendLine("        return 0;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static async ValueTask<int> AwaitValueTaskAsync(ValueTask task)");
        builder.AppendLine("    {");
        builder.AppendLine("        await task.ConfigureAwait(false);");
        builder.AppendLine("        return 0;");
        builder.AppendLine("    }");
    }
