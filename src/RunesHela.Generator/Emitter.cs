using System;
using System.Collections.Generic;
using System.Text;

namespace RunesHela.Generator;

internal static class Emitter
{
    public static string Emit(string appName, IReadOnlyList<CommandNode> roots)
    {
        var allNodes = new List<CommandNode>();
        var indexes = new Dictionary<CommandNode, int>();
        CollectNodes(roots, allNodes, indexes);

        var builder = new StringBuilder(8192);

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Threading;");
        builder.AppendLine("using System.Threading.Tasks;");
        builder.AppendLine();
        builder.AppendLine("namespace RunesHela.Generated;");
        builder.AppendLine();
        builder.AppendLine("internal static class __RunesHelaEntry");
        builder.AppendLine("{");
        builder.Append("    private const string AppName = ").Append(Literal(appName)).AppendLine(";");
        builder.AppendLine();
        AppendConst(builder, "RootHelp", BuildRootHelp(appName, roots));

        for (var i = 0; i < allNodes.Count; i++)
        {
            AppendConst(builder, "Help" + i, BuildNodeHelp(appName, allNodes[i]));
        }

        builder.AppendLine();
        AppendRootRun(builder, roots, indexes);

        for (var i = 0; i < allNodes.Count; i++)
        {
            AppendNodeRun(builder, allNodes[i], i, indexes);
            AppendNodeInvoke(builder, allNodes[i], i);
        }

        AppendWriteHelpers(builder, allNodes);
        AppendAwaitHelpers(builder);

        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("internal static class __RunesHelaModuleInitializer");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void Initialize()");
        builder.AppendLine("    {");
        builder.AppendLine("        global::RunesHela.RunesHelaApp.RegisterEntry(global::RunesHela.Generated.__RunesHelaEntry.RunAsync);");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static void CollectNodes(
        IReadOnlyList<CommandNode> nodes,
        List<CommandNode> allNodes,
        Dictionary<CommandNode, int> indexes)
    {
        foreach (var node in nodes)
        {
            indexes[node] = allNodes.Count;
            allNodes.Add(node);
            CollectNodes(node.Children, allNodes, indexes);
        }
    }

    private static void AppendConst(StringBuilder builder, string name, string value)
    {
        builder.Append("    private const string ").Append(name).Append(" = ").Append(Literal(value)).AppendLine(";");
    }

    private static string BuildRootHelp(string appName, IReadOnlyList<CommandNode> roots)
    {
        var builder = new StringBuilder();
        builder.AppendLine(appName);
        builder.Append("Usage: ").Append(appName).AppendLine(" <command> [options]");
        builder.AppendLine();
        AppendCommandList(builder, roots);
        builder.AppendLine();
        builder.AppendLine("Options:");
        builder.AppendLine("  -h, --help     Show help.");
        builder.AppendLine("      --version  Show version.");
        return builder.ToString();
    }

    private static string BuildNodeHelp(string appName, CommandNode node)
    {
        var builder = new StringBuilder();
        builder.Append("Usage: ").Append(appName).Append(' ').Append(node.Path);

        if (node.Children.Count > 0)
        {
            builder.Append(" [command] [options]");
        }

        builder.AppendLine();

        if (node.Model.Description.Length > 0)
        {
            builder.AppendLine(node.Model.Description);
        }

        if (node.Children.Count > 0)
        {
            builder.AppendLine();
            AppendCommandList(builder, node.Children);
        }

        builder.AppendLine();
        builder.AppendLine("Options:");
        builder.AppendLine("  -h, --help  Show help.");
        return builder.ToString();
    }

    private static void AppendCommandList(StringBuilder builder, IReadOnlyList<CommandNode> nodes)
    {
        var visible = new List<CommandNode>();

        foreach (var node in nodes)
        {
            if (!node.Model.IsHidden)
            {
                visible.Add(node);
            }
        }

        if (visible.Count == 0)
        {
            builder.AppendLine("No commands found.");
            return;
        }

        builder.AppendLine("Commands:");

        var width = 0;
        foreach (var node in visible)
        {
            width = Math.Max(width, node.Model.Name.Length);
        }

        foreach (var node in visible)
        {
            builder.Append("  ").Append(node.Model.Name.PadRight(width));

            if (node.Model.Description.Length > 0)
            {
                builder.Append("  ").Append(node.Model.Description);
            }

            builder.AppendLine();
        }
    }

    private static void AppendRootRun(
        StringBuilder builder,
        IReadOnlyList<CommandNode> roots,
        Dictionary<CommandNode, int> indexes)
    {
        builder.AppendLine("    public static ValueTask<int> RunAsync(string[] args, CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (args.Length == 0)");
        builder.AppendLine("        {");
        builder.AppendLine("            WriteRootHelp();");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        switch (args[0])");
        builder.AppendLine("        {");
        builder.AppendLine("            case \"-h\":");
        builder.AppendLine("            case \"--help\":");
        builder.AppendLine("                WriteRootHelp();");
        builder.AppendLine("                return new ValueTask<int>(0);");
        builder.AppendLine("            case \"--version\":");
        builder.AppendLine("                global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(global::RunesHela.RunesHelaApp.GetVersion());");
        builder.AppendLine("                return new ValueTask<int>(0);");

        var emitted = new HashSet<string>(StringComparer.Ordinal);

        foreach (var root in roots)
        {
            AppendCase(builder, emitted, root.Model.Name, indexes[root], "args");
            foreach (var alias in root.Model.Aliases)
            {
                AppendCase(builder, emitted, alias, indexes[root], "args");
            }
        }

        builder.AppendLine("            default:");
        builder.AppendLine("                WriteUnknownCommand(args[0]);");
        builder.AppendLine("                return new ValueTask<int>(2);");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendCase(
        StringBuilder builder,
        HashSet<string> emitted,
        string name,
        int index,
        string argsVariable)
    {
        if (!emitted.Add(name))
        {
            return;
        }

        builder.Append("            case ").Append(Literal(name)).AppendLine(":");
        builder.Append("                return RunNode").Append(index)
            .Append("Async(").Append(argsVariable).AppendLine(".AsSpan(1), cancellationToken);");
    }

    private static void AppendNodeRun(
        StringBuilder builder,
        CommandNode node,
        int index,
        Dictionary<CommandNode, int> indexes)
    {
        builder.Append("    private static ValueTask<int> RunNode").Append(index)
            .AppendLine("Async(ReadOnlySpan<string> args, CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (args.Length > 0 && (args[0] == \"-h\" || args[0] == \"--help\"))");
        builder.AppendLine("        {");
        builder.Append("            WriteNode").Append(index).AppendLine("Help();");
        builder.AppendLine("            return new ValueTask<int>(0);");
        builder.AppendLine("        }");
        builder.AppendLine();

        if (node.Children.Count == 0)
        {
            builder.Append("        return InvokeNode").Append(index).AppendLine("Async();");
            builder.AppendLine("    }");
            builder.AppendLine();
            return;
        }

        builder.AppendLine("        if (args.Length == 0)");
        builder.AppendLine("        {");

        if (node.Model.HandlerName is not null)
        {
            builder.Append("            return InvokeNode").Append(index).AppendLine("Async();");
        }
        else
        {
            builder.Append("            WriteNode").Append(index).AppendLine("Help();");
            builder.AppendLine("            return new ValueTask<int>(0);");
        }

        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        switch (args[0])");
        builder.AppendLine("        {");

        var emitted = new HashSet<string>(StringComparer.Ordinal);

        foreach (var child in node.Children)
        {
            AppendChildCase(builder, emitted, child.Model.Name, indexes[child]);
            foreach (var alias in child.Model.Aliases)
            {
                AppendChildCase(builder, emitted, alias, indexes[child]);
            }
        }

        builder.AppendLine("            default:");

        if (node.Model.HandlerName is not null)
        {
            builder.Append("                return InvokeNode").Append(index).AppendLine("Async();");
        }
        else
        {
            builder.Append("                WriteUnknownSubcommand(").Append(Literal(node.Path)).AppendLine(", args[0]);");
            builder.AppendLine("                return new ValueTask<int>(2);");
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendChildCase(StringBuilder builder, HashSet<string> emitted, string name, int index)
    {
        if (!emitted.Add(name))
        {
            return;
        }

        builder.Append("            case ").Append(Literal(name)).AppendLine(":");
        builder.Append("                return RunNode").Append(index)
            .AppendLine("Async(args.Slice(1), cancellationToken);");
    }

    private static void AppendNodeInvoke(StringBuilder builder, CommandNode node, int index)
    {
        builder.Append("    private static ValueTask<int> InvokeNode").Append(index).AppendLine("Async()");
        builder.AppendLine("    {");

        if (node.Model.HandlerName is null || node.Model.ReturnKind == HandlerReturnKind.None)
        {
            builder.Append("        global::RunesHela.RunesHelaConsole.Current.Error.WriteLine(")
                .Append(Literal("Command '" + node.Path + "' is not implemented."))
                .AppendLine(");");
            builder.AppendLine("        return new ValueTask<int>(1);");
            builder.AppendLine("    }");
            builder.AppendLine();
            return;
        }

        if (!node.Model.IsStatic)
        {
            builder.Append("        var command = new ").Append(node.Model.TypeFullName).AppendLine("();");
        }

        var receiver = node.Model.IsStatic ? node.Model.TypeFullName : "command";
        var call = receiver + "." + node.Model.HandlerName + "()";

        switch (node.Model.ReturnKind)
        {
            case HandlerReturnKind.Void:
                builder.Append("        ").Append(call).AppendLine(";");
                builder.AppendLine("        return new ValueTask<int>(0);");
                break;

            case HandlerReturnKind.Int:
                builder.Append("        return new ValueTask<int>(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.Task:
                builder.Append("        return AwaitTaskAsync(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.TaskOfInt:
                builder.Append("        return new ValueTask<int>(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.ValueTask:
                builder.Append("        return AwaitValueTaskAsync(").Append(call).AppendLine(");");
                break;

            case HandlerReturnKind.ValueTaskOfInt:
                builder.Append("        return ").Append(call).AppendLine(";");
                break;
        }

        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendWriteHelpers(StringBuilder builder, IReadOnlyList<CommandNode> nodes)
    {
        builder.AppendLine("    private static void WriteRootHelp()");
        builder.AppendLine("    {");
        builder.AppendLine("        global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(RootHelp);");
        builder.AppendLine("    }");
        builder.AppendLine();

        for (var i = 0; i < nodes.Count; i++)
        {
            builder.Append("    private static void WriteNode").Append(i).AppendLine("Help()");
            builder.AppendLine("    {");
            builder.Append("        global::RunesHela.RunesHelaConsole.Current.Out.WriteLine(Help").Append(i).AppendLine(");");
            builder.AppendLine("    }");
            builder.AppendLine();
        }

        builder.AppendLine("    private static void WriteUnknownCommand(string command)");
        builder.AppendLine("    {");
        builder.AppendLine("        var error = global::RunesHela.RunesHelaConsole.Current.Error;");
        builder.AppendLine("        error.Write(\"Unknown command '\");");
        builder.AppendLine("        error.Write(command);");
        builder.AppendLine("        error.WriteLine(\"'.\");");
        builder.AppendLine("        error.Write(\"Run '\");");
        builder.AppendLine("        error.Write(AppName);");
        builder.AppendLine("        error.WriteLine(\" --help' to list commands.\");");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static void WriteUnknownSubcommand(string path, string command)");
        builder.AppendLine("    {");
        builder.AppendLine("        var error = global::RunesHela.RunesHelaConsole.Current.Error;");
        builder.AppendLine("        error.Write(\"Unknown command '\");");
        builder.AppendLine("        error.Write(path);");
        builder.AppendLine("        error.Write(\" \");");
        builder.AppendLine("        error.Write(command);");
        builder.AppendLine("        error.WriteLine(\"'.\");");
        builder.AppendLine("        error.Write(\"Run '\");");
        builder.AppendLine("        error.Write(AppName);");
        builder.AppendLine("        error.Write(\" \");");
        builder.AppendLine("        error.Write(path);");
        builder.AppendLine("        error.WriteLine(\" --help' to list subcommands.\");");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendAwaitHelpers(StringBuilder builder)
    {
        builder.AppendLine("    private static async ValueTask<int> AwaitTaskAsync(Task task)");
        builder.AppendLine("    {");
        builder.AppendLine("        await task.ConfigureAwait(false);");
        builder.AppendLine("        return 0;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static async ValueTask<int> AwaitValueTaskAsync(ValueTask task)");
        builder.AppendLine("    {");
        builder.AppendLine("        await task.ConfigureAwait(false);");
        builder.AppendLine("        return 0;");
        builder.AppendLine("    }");
    }

    private static string Literal(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');

        foreach (var c in value)
        {
            switch (c)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\r':
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    builder.Append(c);
                    break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }
}
