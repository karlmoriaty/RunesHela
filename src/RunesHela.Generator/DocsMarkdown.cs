using System;
using System.Collections.Generic;
using System.Text;

namespace RunesHela.Generator;

internal static class DocsMarkdown
{
    public static string Build(string appName, IReadOnlyList<CommandNode> roots)
    {
        var builder = new StringBuilder();
        builder.Append("# ").AppendLine(appName);
        builder.AppendLine();
        builder.AppendLine("Generated by RunesHela. Do not edit by hand.");
        builder.AppendLine();

        foreach (var root in roots)
        {
            AppendNode(builder, appName, root, depth: 1);
        }

        return builder.ToString().Replace("\r\n", "\n");
    }

    private static void AppendNode(StringBuilder builder, string appName, CommandNode node, int depth)
    {
        var heading = new string('#', Math.Min(depth + 1, 6));
        builder.Append(heading).Append(' ').AppendLine(node.Path);
        builder.AppendLine();

        if (node.Model.Description.Length > 0)
        {
            builder.AppendLine(node.Model.Description);
            builder.AppendLine();
        }

        builder.Append("**Usage:** `").Append(appName).Append(' ').Append(node.Path).AppendLine(" [options]`");
        builder.AppendLine();

        if (node.Model.Parameters.Count > 0)
        {
            builder.AppendLine("### Arguments");
            builder.AppendLine();
            builder.AppendLine("| Name | Type | Required | Default | Description |");
            builder.AppendLine("| --- | --- | --- | --- | --- |");

            foreach (var parameter in node.Model.Parameters)
            {
                builder.Append("| `").Append(parameter.Name).Append("` | `").Append(TypeName(parameter.Type)).Append("` | ")
                    .Append(parameter.IsRequired ? "yes" : "no").Append(" | ");

                if (parameter.HasDefault)
                {
                    builder.Append('`').Append(parameter.DefaultDisplay).Append('`');
                }

                builder.Append(" | ").Append(Escape(parameter.Description)).AppendLine(" |");
            }

            builder.AppendLine();
        }

        builder.AppendLine("### Options");
        builder.AppendLine();
        builder.AppendLine("| Option | Type | Required | Default | Env | Description |");
        builder.AppendLine("| --- | --- | --- | --- | --- | --- |");

        foreach (var option in node.Model.Options)
        {
            if (option.IsHidden)
            {
                continue;
            }

            builder.Append("| `");
            builder.Append(option.ShortName == '\0' ? "--" + option.LongName : "-" + option.ShortName + ", --" + option.LongName);
            builder.Append("` | `").Append(TypeName(option.Type)).Append("` | ")
                .Append(option.IsRequired ? "yes" : "no").Append(" | ");

            if (option.HasDefault)
            {
                builder.Append('`').Append(option.IsSecret ? "***" : option.DefaultDisplay).Append('`');
            }

            builder.Append(" | ");
            builder.Append(option.EnvVar is null ? string.Empty : "`" + option.EnvVar + "`");
            builder.Append(" | ").Append(Escape(option.Description)).AppendLine(" |");
        }

        builder.AppendLine();

        if (node.Children.Count > 0)
        {
            builder.AppendLine("### Commands");
            builder.AppendLine();

            foreach (var child in node.Children)
            {
                if (!child.Model.IsHidden)
                {
                    builder.Append("- `").Append(child.Model.Name).Append("` — ").AppendLine(child.Model.Description);
                }
            }

            builder.AppendLine();
        }

        foreach (var child in node.Children)
        {
            AppendNode(builder, appName, child, depth + 1);
        }
    }

    private static string TypeName(TypeModel type)
    {
        const string prefix = "global::";
        var name = type.DisplayName.StartsWith(prefix, StringComparison.Ordinal)
            ? type.DisplayName.Substring(prefix.Length)
            : type.DisplayName;

        return Escape(name);
    }

    private static string Escape(string value)
    {
        return value.Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");
    }
}
