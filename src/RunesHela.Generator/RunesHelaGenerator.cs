using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace RunesHela.Generator;

/// <summary>
/// Incremental generator that discovers <c>[Command]</c> classes and emits the application entry point.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class RunesHelaGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(
            "RunesHela.CommandAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, cancellationToken) =>
                CommandModelFactory.Create(attributeContext, cancellationToken));

        var configFile = context.CompilationProvider.Select(
            static (compilation, _) => ReadConfigFileName(compilation));

        context.RegisterSourceOutput(
            candidates.Collect().Combine(configFile),
            static (sourceContext, items) => Emit(sourceContext, items.Left, items.Right));
    }

    private static string? ReadConfigFileName(Compilation compilation)
    {
        foreach (var attribute in compilation.Assembly.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() != "RunesHela.RunesHelaConfigFileAttribute")
            {
                continue;
            }

            var name = attribute.ConstructorArguments.Length > 0
                ? attribute.ConstructorArguments[0].Value as string
                : null;

            return string.IsNullOrWhiteSpace(name) ? "appsettings.json" : name!.Trim();
        }

        return null;
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<CommandCandidate> candidates, string? configFileName)
    {
        try
        {
            EmitCore(context, candidates, configFileName);
        }
        catch (Exception exception)
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Diagnostics.GeneratorError,
                Location.None,
                exception.GetType().Name + ": " + exception.Message));

            context.AddSource(
                "RunesHela.Entry.g.cs",
                SourceText.From(
                    "// <auto-generated/>\n// RunesHela generator failed. See diagnostic RHL999.\n",
                    Encoding.UTF8));
        }
    }

    private static void EmitCore(
        SourceProductionContext context,
        ImmutableArray<CommandCandidate> candidates,
        string? configFileName)
    {
        var models = new List<CommandModel>();

        foreach (var candidate in candidates)
        {
            foreach (var diagnostic in candidate.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (candidate.Model is not null)
            {
                models.Add(candidate.Model);
            }
        }

        var nodes = new Dictionary<string, CommandNode>(StringComparer.Ordinal);

        foreach (var model in models)
        {
            nodes[model.TypeFullName] = new CommandNode(model);
        }

        var roots = new List<CommandNode>();

        foreach (var model in models)
        {
            var node = nodes[model.TypeFullName];

            if (model.ParentTypeFullName is null)
            {
                roots.Add(node);
            }
            else if (nodes.TryGetValue(model.ParentTypeFullName, out var parent))
            {
                parent.Children.Add(node);
            }
            else
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    Diagnostics.NestedParentNotCommand,
                    model.Location.ToLocation(),
                    model.Name));
            }
        }

        foreach (var root in roots)
        {
            AssignPath(root, root.Model.Name);
        }

        ValidateSiblings(context, roots);

        foreach (var root in roots)
        {
            ValidateTree(context, root);
        }

        var appName = models.Count > 0 ? models[0].AppName : "app";
        var source = Emitter.Emit(appName, roots, configFileName);

        context.AddSource("RunesHela.Entry.g.cs", SourceText.From(source, Encoding.UTF8));
    }

    private static void AssignPath(CommandNode node, string path)
    {
        node.Path = path;

        foreach (var child in node.Children)
        {
            AssignPath(child, path + " " + child.Model.Name);
        }
    }

    private static void ValidateSiblings(SourceProductionContext context, List<CommandNode> siblings)
    {
        var names = new Dictionary<string, CommandNode>(StringComparer.Ordinal);

        foreach (var sibling in siblings)
        {
            if (!names.ContainsKey(sibling.Model.Name))
            {
                names.Add(sibling.Model.Name, sibling);
            }
            else
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    Diagnostics.DuplicateCommandName,
                    sibling.Model.Location.ToLocation(),
                    sibling.Model.Name));
            }
        }

        var aliases = new Dictionary<string, CommandNode>(StringComparer.Ordinal);

        foreach (var sibling in siblings)
        {
            foreach (var alias in sibling.Model.Aliases)
            {
                if (names.ContainsKey(alias) || aliases.ContainsKey(alias))
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        Diagnostics.AliasConflictsWithSibling,
                        sibling.Model.Location.ToLocation(),
                        alias,
                        sibling.Model.Name));
                }
                else
                {
                    aliases.Add(alias, sibling);
                }
            }
        }

        foreach (var sibling in siblings)
        {
            ValidateSiblings(context, sibling.Children);
        }
    }

    private static void ValidateTree(SourceProductionContext context, CommandNode node)
    {
        if (node.Children.Count == 0 && node.Model.HandlerName is null)
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Diagnostics.NoHandler,
                node.Model.Location.ToLocation(),
                node.Path));
        }

        foreach (var child in node.Children)
        {
            ValidateTree(context, child);
        }
    }
}
